def split_into_sentences(text):
    raw = re.split(r'(?<=[.?!।—])\s+', text)
    chunks = []
    curr = ''
    for piece in raw:
        piece = piece.strip()
        if not piece or all(c in '.?!।— ,;: \t\n' for c in piece):
            continue
        if len(curr) + len(piece) < 150:
            curr = (curr + ' ' + piece).strip()
        else:
            if curr:
                chunks.append(curr.strip())
            curr = piece
    if curr.strip() and not all(c in '.?!।— ,;: \t\n' for c in curr):
        chunks.append(curr.strip())
    return chunks

def generate_chunk_audio(chunk, out_path, speed=1.02):
    max_attempts = len(ACCOUNTS) * 2
    attempts = 0
    while attempts < max_attempts:
        acc = get_current_account()
        headers = {
            "Authorization": f"Bearer {acc['apiKey']}",
            "Content-Type": "application/json",
            "Accept": "audio/wav"
        }
        payload = {
            "text": chunk,
            "voice_id": acc["voiceId"],
            "model": "lightning_v3.1_pro",
            "speed": speed,
            "sample_rate": 24000,
            "output_format": "wav"
        }
        try:
            data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(URL, data=data, headers=headers, method="POST")
            with urllib.request.urlopen(req, timeout=30) as resp:
                wav_data = resp.read()
                with open(out_path, "wb") as f:
                    f.write(wav_data)
            # Verify RIFF
            with wave.open(out_path, "rb") as w:
                _ = w.getnframes()
            return True
        except urllib.error.HTTPError as e:
            attempts += 1
            print(f"   ⚠️ HTTP {e.code} on {acc['name']} -> Failover")
            rotate_account()
        except Exception as e:
            attempts += 1
            print(f"   ⚠️ Error on {acc['name']}: {e} -> Failover")
            rotate_account()
        time.sleep(0.5)
    return False

def merge_wavs(wav_files, out_path, silence_ms=450):
    if not wav_files:
        print("❌ No wav files to merge!")
        return 0
    
    silence_frames = int(24000 * (silence_ms / 1000.0))
    silence_bytes = b'\x00\x00' * silence_frames
    
    total_frames = 0
    with wave.open(out_path, 'wb') as outfile:
        outfile.setnchannels(1)
        outfile.setsampwidth(2)
        outfile.setframerate(24000)
        
        for i, f in enumerate(wav_files):
            try:
                with wave.open(f, 'rb') as infile:
                    nframes = infile.getnframes()
                    data = infile.readframes(nframes)
                    outfile.writeframes(data)
                    total_frames += nframes
                    if i < len(wav_files) - 1:
                        outfile.writeframes(silence_bytes)
                        total_frames += silence_frames
            except Exception as e:
                print(f"   ⚠️ Error reading {f}: {e}")
                
    duration_sec = total_frames / 24000.0
    print(f"🎉 Merged {len(wav_files)} files into {out_path} ({duration_sec:.2f}s)")
    return duration_sec


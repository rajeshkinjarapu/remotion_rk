def main():
    mgr = CartesiaVoiceManager(CARTESIA_PAIRS)
    results = []
    
    print("\n=======================================================")
    print("🎙️ Generating Synced Chapter Audio for Srikakulam (32 Chapters)")
    print("=======================================================")

    wav_files = []
    total_chars = sum(len(c["text"]) for c in SRIKAKULAM_32_CHAPTERS)
    print(f"Total script characters: {total_chars}")

    for ch in SRIKAKULAM_32_CHAPTERS:
        cid = ch["id"]
        title = ch["title"]
        text = ch["text"]
        
        raw_wav = os.path.join(OUT_DIR, f"ch_{cid:02d}_raw.wav")
        clean_wav = os.path.join(OUT_DIR, f"ch_{cid:02d}.wav")
        wav_files.append(clean_wav)

        print(f"▶ Ch {cid:02d}: '{title}' ({len(text)} chars)...")
        audio_bytes, used_key, voice_name = mgr.synthesize(text)
        with open(raw_wav, 'wb') as f:
            f.write(audio_bytes)

        # Convert to 24000Hz mono WAV
        cmd = [
            FFMPEG, "-y", "-i", raw_wav,
            "-ar", "24000", "-ac", "1",
            clean_wav
        ]
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        if os.path.exists(raw_wav):
            os.remove(raw_wav)

        # Measure exact duration
        with wave.open(clean_wav, 'rb') as w:
            n_frames = w.getnframes()
            rate = w.getframerate()
            dur_sec = n_frames / float(rate)
            # Add 0.3s (9 frames) natural breath pause so visuals don't cut immediately on the last consonant
            pad_sec = 0.3
            dur_frames = int(round((dur_sec + pad_sec) * 30))

        results.append({
            "id": cid,
            "title": title,
            "durationSec": round(dur_sec, 2),
            "totalSec": round(dur_sec + pad_sec, 2),
            "durationFrames": dur_frames,
            "audioPath": f"audio/srikakulam/chapters/ch_{cid:02d}.wav"
        })
        print(f"   ✓ Audio: {dur_sec:.2f}s -> {dur_frames} frames")

    # Compute timeline starts and total frames
    starts = []
    acc_frames = 0
    for r in results:
        starts.append(acc_frames)
        r["startFrame"] = acc_frames
        acc_frames += r["durationFrames"]

    total_frames = acc_frames
    total_sec = total_frames / 30.0

    print(f"\n=======================================================")
    print(f"Total Video Duration: {total_sec:.2f}s ({total_frames} frames @ 30 FPS)")
    print(f"=======================================================")

    # Save timings.json
    timings_path = "public/audio/srikakulam/srikakulam_timings.json"
    data = {
        "totalFrames": total_frames,
        "totalSec": round(total_sec, 2),
        "fps": 30,
        "chapters": results
    }
    with open(timings_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"✓ Timings saved to {timings_path}")

    # Also build a perfectly synced master_complete_audio.wav
    # by concatenating the 32 WAV files with the exact padding
    concat_list = os.path.join(OUT_DIR, "concat_list.txt")
    with open(concat_list, 'w', encoding='utf-8') as f:
        for w in wav_files:
            abs_w = os.path.abspath(w).replace('\\', '/')
            f.write(f"file '{abs_w}'\n")

    master_wav = "public/audio/srikakulam/master_complete_audio.wav"
    concat_cmd = [
        FFMPEG, "-y", "-f", "concat", "-safe", "0",
        "-i", concat_list,
        "-c", "copy",
        master_wav
    ]
    subprocess.run(concat_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    if os.path.exists(concat_list):
        os.remove(concat_list)
    print(f"✓ Synced master audio saved to {master_wav}")

    print("\n================ CREDIT USAGE REPORT ================")
    for key, used in mgr.usage.items():
        if used > 0:
            print(f"• Key {key[:14]}...: {used} characters (credits) used")
    print(f"• Active Key Index: {mgr.idx + 1} of {len(CARTESIA_PAIRS)}")
    remaining_keys = len(CARTESIA_PAIRS) - (mgr.idx + (1 if mgr.usage[mgr.pairs[mgr.idx][0]] > 0 else 0))
    print(f"• Completely Unused Fresh Keys remaining: {remaining_keys} keys")
    print("=====================================================")

if __name__ == "__main__":
    main()
